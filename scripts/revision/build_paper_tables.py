def split_table(out: Path) -> None:
    staged = pd.read_csv(ANALYSIS / "splits/staged_macro_f1_summary.csv").set_index(["level", "architecture"])
    crossing = pd.read_csv(REVISION / "splits/group_crossings.csv")
    composition = pd.read_csv(ANALYSIS / "splits/split_composition.csv")
    standardised = pd.read_csv(ANALYSIS / "splits/standardised_macro_f1_summary.csv")
    rows = []
    for level, name, links in LEVELS:
        cross = crossing[(crossing["setting"] == level) & (crossing["group_column"] == "capture_group_id")].iloc[0]
        test = composition[(composition["setting"] == level) & (composition["split"] == "test")].iloc[0]
        cells = [name, links, str(int(cross["crossing_groups"])), f"{100 * test['Fresh_share']:.1f}"]
        for arch in ("mobilenet_v2", "convnext_tiny"):
            row = staged.loc[(level, arch)]
            cells.append(pm(row["macro_f1_mean"], row["macro_f1_sd"]))
        rows.append(" & ".join(cells) + r" \\")
    l4 = standardised[(standardised["task"] == "three_stage") & (standardised["setting"] == "L4_capture")].set_index("architecture")
    rows.append(
        r"\multicolumn{4}{@{}l}{L4, composition-standardized} & "
        + " & ".join(pm(l4.loc[arch, "standardised_macro_f1_mean"], l4.loc[arch, "standardised_macro_f1_sd"]) for arch in ("mobilenet_v2", "convnext_tiny"))
        + r" \\"
    )
    linkage = pd.read_csv(ANALYSIS / "splits/leakage_linkage_summary.csv")
    linked = linkage[(linkage["level"] == "L0_naive") & (linkage["architecture"] == "mobilenet_v2")].set_index("subset")
    body = [
        r"\begin{tabular}{@{}llcccc@{}}",
        r"\toprule",
        r"\textbf{Level} & \textbf{Links} & \textbf{Cr.} & \textbf{F\%} & \textbf{MobileNetV2} & \textbf{ConvNeXt-Tiny} \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
    ]
    note = (
        "Cumulative link sets; Cr.: capture groups crossing partitions; F\\%: Fresh share of the test set; macro-F1 "
        "mean $\\pm$ SD over three seeds on each level's own test set. Standardized: test reweighted to the dataset's "
        f"produce-by-stage composition. In L0, {int(linked.loc['capture_linked', 'images'])} of "
        f"{int(linked.loc['all', 'images'])} test images share a capture group with a training image."
    )
    wrap(out / "paper_split_table.tex", caption="Staged Grouping Ablation (Three-Stage Test Macro-F1)", label="tab:split", body=body, note=note)


