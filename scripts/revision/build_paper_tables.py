def pm(mean: float, sd: float, digits: int = 3) -> str:
    return rf"${mean:.{digits}f}\pm{sd:.{digits}f}$"


def ci(low: float, high: float, digits: int = 3) -> str:
    return rf"$[{low:.{digits}f}, {high:.{digits}f}]$"


def signed(value: float, digits: int = 3) -> str:
    return rf"${value:+.{digits}f}$".replace("+-", "-")


def count(value: float) -> str:
    return f"{int(round(value)):,}"


def wrap(
    path: Path,
    *,
    caption: str,
    label: str,
    body: list[str],
    wide: bool = False,
    note: str | None = None,
    size: str = r"\footnotesize",
) -> None:
    environment = "table*" if wide else "table"
    lines = [
        "% Auto-generated by scripts/revision/build_paper_tables.py; do not edit by hand.",
        rf"\begin{{{environment}}}[t]",
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
        r"\centering",
        size,
        r"\setlength{\tabcolsep}{2.6pt}",
        *body,
    ]
    if note:
        lines.append(rf"\par\smallskip\parbox{{\linewidth}}{{\scriptsize {note}}}")
    lines.append(rf"\end{{{environment}}}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


