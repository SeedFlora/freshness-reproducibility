        r"\begin{tabular}{@{}lrrr@{}}",
        r"\toprule",
        r"\multicolumn{3}{@{}l}{\textbf{Audit step}} & \textbf{Images} \\",
        r"\midrule",
        rf"\multicolumn{{3}}{{@{{}}l}}{{Decodable archived JPEGs (8 produce $\times$ 3 stages)}} & {count(archived)} \\",
        rf"\multicolumn{{3}}{{@{{}}l}}{{Repository augmentations (\texttt{{aug\_}}) excluded}} & {count(augmented)} \\",
        rf"\multicolumn{{3}}{{@{{}}l}}{{Cross-label exact duplicates excluded ({conflicts['shared_sha256'].nunique()} identities)}} & {count(len(conflicts))} \\",
